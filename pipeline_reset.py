"""pipeline_reset.py
v1.0.9 [Reset pipeline training] (sidebar, File menu, code 30), mixed into CrackSegmentation.
Brings the dataset back to its starting point: every file in 'Training set', 'Validation set' and 'Test set'
(their 'Images', 'JSON files' and 'Binary files') goes back to the working 'Images', 'JSON files' and
'Binary files' folders. The cross-validation output of the Training set ('folds.csv' and the 'folds' copies)
describes a split that no longer exists, so it is removed. A file whose name already exists in the working
folder is never overwritten: it stays in its set and is listed. Emptied set folders are removed.
Shows what will move and asks first; works in either mode, also on the "No photo left" screen.
"""
import os
import shutil

from config import IMAGES_DIR_NAME, JSON_DIR_NAME, BINARY_DIR_NAME


RESET_PIPELINE_CODE = 30
SET_SUBFOLDERS = (IMAGES_DIR_NAME, JSON_DIR_NAME, BINARY_DIR_NAME)
SPLITS = ("training", "validation", "test")


def files_in(folder):
    return sorted(f for f in os.listdir(folder) if os.path.isfile(os.path.join(folder, f))) \
        if os.path.isdir(folder) else []


class PipelineResetMixin:
    """[Reset pipeline training]. Relies on DatasetSplitMixin._split_root() and cfg."""

    def _reset_plan(self):
        """{'moves': [(src, dest)], 'conflicts': [src], 'counts': {split: photos}, 'folds': [paths to remove]}."""
        work = str(self.cfg.SCRIPT_DIR)
        moves, conflicts, counts = [], [], {}
        for split in SPLITS:
            root = self._split_root(split)
            counts[split] = len(files_in(os.path.join(root, IMAGES_DIR_NAME)))
            for sub in SET_SUBFOLDERS:
                for name in files_in(os.path.join(root, sub)):
                    src, dest = os.path.join(root, sub, name), os.path.join(work, sub, name)
                    if os.path.exists(dest):
                        conflicts.append(src)
                    else:
                        moves.append((src, dest))
        training = self._split_root("training")
        folds = [p for p in (os.path.join(training, self.cfg.CV_FOLDS_FILE), os.path.join(training, self.cfg.CV_FOLDS_DIR))
                 if os.path.exists(p)]
        return {"moves": moves, "conflicts": conflicts, "counts": counts, "folds": folds}

    def _reset_message(self, plan):
        names = self.cfg.DATASET_SPLIT_DIRS
        lines = ["Bring every file of the sets back to 'Images', 'JSON files' and 'Binary files'?", ""]
        lines += [f"{names[s]}: {plan['counts'][s]} photo(s)" for s in SPLITS]
        lines.append(f"\n{len(plan['moves'])} file(s) in all (photos, JSON, masks).")
        if plan["folds"]:
            lines.append("The cross-validation folds (folds.csv and the 'folds' copies) are removed: "
                         "press CV folds again after the next split.")
        if plan["conflicts"]:
            lines.append(f"{len(plan['conflicts'])} file(s) already exist in the working folders: "
                         "they are not overwritten and stay in their set.")
        return "\n".join(lines)

    # --- dialogs (a GUI wrapper overrides them) ---------------------------------------------

    def _confirm_reset_pipeline(self, message):
        print("\n" + message)
        try:
            return input("Type y to reset the sets, or ENTER to cancel: ").strip().lower() in ("y", "s")
        except EOFError:
            return False

    def _notify_reset_pipeline(self, message):
        print(message)

    # --- the button -----------------------------------------------------------------------

    def _apply_reset(self, plan):
        moved, errors = 0, []
        for src, dest in plan["moves"]:
            try:
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                shutil.move(src, dest)
                moved += 1
            except OSError as e:
                errors.append(f"{os.path.basename(src)}: {e}")
        for path in plan["folds"]:
            shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)   # generated by CV folds only
        self._remove_empty_set_folders()
        return moved, errors

    def _remove_empty_set_folders(self):
        for split in SPLITS:
            root = self._split_root(split)
            for folder in [os.path.join(root, sub) for sub in SET_SUBFOLDERS] + [root]:
                if os.path.isdir(folder) and not os.listdir(folder):
                    os.rmdir(folder)

    def run_reset_pipeline(self):
        """Code 30. Returns True when files were moved back (the image queue must then be reloaded)."""
        if not self.cfg.queue_idle and self.cfg.CURRENT_IMAGE_PATH and not self._settle_unsaved_changes("the reset"):
            print(" [RESET PIPELINE] Cancelled: nothing moved.")
            return False
        plan = self._reset_plan()
        if not plan["moves"] and not plan["folds"]:
            self._notify_reset_pipeline("The Training, Validation and Test sets are already empty: nothing to reset.")
            return False
        if not self._confirm_reset_pipeline(self._reset_message(plan)):
            print(" [RESET PIPELINE] Cancelled: nothing moved.")
            return False
        moved, errors = self._apply_reset(plan)
        self._all_segmented_cache = None
        problems = errors + [f"{os.path.basename(p)}: already in the working folder" for p in plan["conflicts"]]
        summary = f"{moved} file(s) moved back to 'Images', 'JSON files' and 'Binary files'." + (
            f"\n{len(problems)} left in the sets:\n" + "\n".join(problems[:8]) if problems else "")
        print(f" [RESET PIPELINE] {summary}")
        self._notify_reset_pipeline(summary)
        return moved > 0
